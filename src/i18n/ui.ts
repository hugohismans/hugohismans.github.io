const DICT: Record<Lang, Record<UIKey, string>> = { fr, en };

/** Renvoie la fonction de traduction d'une langue. */
export function useT(lang: Lang) {
  return (key: UIKey, vars: Record<string, string | number> = {}) => fill(DICT[lang][key] ?? DICT.fr[key], vars);
}

export function fill(s: string, vars: Record<string, string | number>) {
  return s.replace(/\{(\w+)\}/g, (_, k: string) => (k in vars ? String(vars[k]) : `{${k}}`));
}

/** Chemins équivalents d'une langue à l'autre. */
export const ROUTES = {
  home: { fr: '/', en: '/en/' },
  project: (slug: string, lang: Lang) => (lang === 'fr' ? `/projets/${slug}/` : `/en/projects/${slug}/`),
} as const;

export const otherLang = (lang: Lang): Lang => (lang === 'fr' ? 'en' : 'fr');
